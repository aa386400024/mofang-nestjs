/**
 * 词库自检: 确认词库自身符合命名规则.
 *
 * 为什么要自检: 词库是**人工挑**的, 而"挑的时候没注意到首字是姓"这类疏漏一定会发生.
 * 让它像内容基线一样在灌库/上线前就炸, 比事后在图鉴上看到一个「李然」再返工便宜得多.
 *
 * @returns 全部合规返回 null; 否则返回首个问题描述
 */
export function validateCodenameBank(): string | null {
  const seen = new Set<string>();

  for (const word of VISITOR_POOL_CODENAME_BANK) {
    if (!isAcceptableNameBody(word)) {
      return (
        `词库里的「${word}」不符合命名规则 (形态 1-3 字 / 不以姓氏开头 / 不含强性别字 / ` +
        '不含性格评价字 (强/倔/傲/烈) / 无称谓 / 无系统标签)'
      );
    }
    if (seen.has(word)) {
      return `词库里出现重名: ${word}`;
    }
    seen.add(word);
  }

  return null;
}
