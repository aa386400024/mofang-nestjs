/** 代号主体允许的最小/最大字数 (不含去重尾号). 规则: 2-3 字为主, 可单字/叠字. */
const NAME_MIN_LENGTH = 1;
const NAME_MAX_LENGTH = 3;

/** 去重尾号格式: 「晚晴 · 07」. */
const DEDUP_SEPARATOR = ' · ';

/** 去重尾号起始序号 (无尾号的主体算第 1 个). */
const DEDUP_START = 2;

/** 去重尾号最大序号 (超出后不再补零). */
const DEDUP_MAX = 99;

/**
 * 判定一个代号**主体**是否合规 (不含去重尾号).
 *
 * @param value 代号主体
 */
function isAcceptableNameBody(value: string): boolean {
  if (value.length < NAME_MIN_LENGTH || value.length > NAME_MAX_LENGTH) {
    return false;
  }
  // 纯中文 (规则要求"中文称呼感"; 字母/数字混入会变成"系统生成串")
  if (!/^[一-龥]+$/.test(value)) {
    return false;
  }
  if (COMMON_SURNAMES.has(value.slice(0, 1))) {
    return false;
  }
  for (const char of value) {
    if (GENDERED_CHARACTERS.has(char)) {
      return false;
    }
    if (PERSONALITY_OR_HARSH_CHARACTERS.has(char)) {
      return false;
    }
  }
  if (FORBIDDEN_WORDS.some((word) => value.includes(word))) {
    return false;
  }
  // 主体里不允许出现分隔符 —— 「 · 」是去重尾号的专用形态, 出现在主体里说明
  // 有人把系统标签写进了名字.
  if (value.includes('·')) {
    return false;
  }
  return true;
}

/**
 * 判定一个完整代号 (可含去重尾号) 是否合规.
 *
 * 用于三处: ① 词库自检 ② LLM 产出的代号闸门 ③ 最终落库前的兜底.
 *
 * @param value 完整代号
 */
export function isAcceptableCodename(value: string): boolean {
  const body = stripDedupSuffix(value);
  if (body === null) {
    return false;
  }
  return isAcceptableNameBody(body);
}

/**
 * 去掉去重尾号, 返回代号主体; 形态不合法时返回 null.
 *
 * @param value 完整代号
 */
function stripDedupSuffix(value: string): string | null {
  const index = value.lastIndexOf(DEDUP_SEPARATOR);
  if (index === -1) {
    return value;
  }
  const suffix = value.slice(index + DEDUP_SEPARATOR.length);
  if (!/^\d{2}$/.test(suffix)) {
    return null;
  }
  return value.slice(0, index);
}

