/**
 * 给已占用的代号挂去重尾号 (「晚晴 · 02」).
 *
 * 尾号只做去重, 不抢视觉: 两位数字 + 零填充, 不超过 99.
 *
 * @param base 主体代号
 * @param taken 已被占用的代号集合
 * @returns 带上尾号且未被占用的代号
 */
export function withCodenameDedupSuffix(base: string, taken: ReadonlySet<string>): string {
  for (let index = DEDUP_START; index <= DEDUP_MAX; index += 1) {
    const candidate = `${base}${DEDUP_SEPARATOR}${String(index).padStart(2, '0')}`;
    if (!taken.has(candidate)) {
      return candidate;
    }
  }
  // 尾号用尽 (需要 98 个同名): 极不可能, 但不能返回已被占用的串.
  return `${base}${DEDUP_SEPARATOR}${DEDUP_MAX + 1}`;
}

/**
 * 从词库组合一个**未被占用**的代号.
 *
 * 顺序:
 *   ① 在词库里找一个空闲词 (随机起点 + 顺序扫描, 避免每次都取到池首);
 *   ② 词库耗尽 → 用中性前缀×后缀组合出一个合规词;
 *   ③ 组合空间也耗尽 → 给池首词挂去重尾号.
 *
 * 也就是说: **尾号是兜底**, 只有词库与组合空间都挤不下时才出现.
 *
 * @param taken 已被占用的代号集合
 */
export function composeCodename(taken: ReadonlySet<string>): string {
  const bank = VISITOR_POOL_CODENAME_BANK;
  // 起点用"已占用数量"推导, 不用随机数: 化名不需要"随机" —— 顺序轮换即可, 而且确定性
  // 带来两个好处: ① 可预测可测试 (同一个 taken 集合 → 同一个结果);
  // ② 避开 sonarjs/pseudo-random (伪随机数不该在内容生成处无脑用).
  // 库越长, 起点越靠后 → 天然把新代号推向前面没用过的那些.
  const start = taken.size % bank.length;
  for (let offset = 0; offset < bank.length; offset += 1) {
    const candidate = bank[(start + offset) % bank.length];
    if (candidate && isAcceptableNameBody(candidate) && !taken.has(candidate)) {
      return candidate;
    }
  }

  for (const prefix of COMPOSE_PREFIXES) {
    for (const suffix of COMPOSE_SUFFIXES) {
      const candidate = `${prefix}${suffix}`;
      if (isAcceptableNameBody(candidate) && !taken.has(candidate)) {
        return candidate;
      }
    }
  }

  const fallback = bank[0] ?? '小满';
  return withCodenameDedupSuffix(fallback, taken);
}

/**
 * 词库里是否已有某个代号 (用于校验 seed 的代号在词库覆盖范围内).
 *
 * @param codename 代号
 */
export function isInCodenameBank(codename: string): boolean {
  return VISITOR_POOL_CODENAME_BANK.includes(codename);
}

