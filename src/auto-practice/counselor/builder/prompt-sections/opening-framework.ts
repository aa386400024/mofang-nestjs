import { targetTurnsBandText, type SessionProfile } from '../../../session-profile.js';
import type { PromptSection } from '../../dto/counselor-types.js';

/**
 * 开场知情框架 (AF-129 · 按会话档案动态生成).
 *
 * ── 为什么需要它 ──────────────────────────────────────────────────────────
 *   AF-125 跨模型预评审与 AF-127 结构审计都指向同一个产品层缺口:
 *   16 场 long packet 里, 保密与例外 / 边界 / 时长与频率 / 可暂停与可拒答 /
 *   录音与知情同意 **五项全部 0/16** —— 不是模型不会共情, 而是 prompt 从没要求
 *   咨询师在开场把咨询框架说清楚.
 *
 * ── 为什么对 legacy 关闭 ─────────────────────────────────────────────────
 *   legacy 是缺省档, 行为必须与 2026-11-18 之前逐字一致; 开场框架只在
 *   standard / long 这类长会话档案里启用 (判据 = targetTurnsBand 是否存在).
 *
 * ── 口径边界 ──────────────────────────────────────────────────────────────
 *   本块只给"说什么"的结构纪律, 不做临床质量判断; 命中结构 ≠ 临床达标.
 *   来访者处于危机时, 先做安全评估与稳定化, 再把框架补上.
 *
 * @param profile 会话档案
 * @returns prompt 纪律块 (legacy 档时 enabled=false)
 */
export function sessionOpeningFrameworkSection(profile: SessionProfile): PromptSection {
  const band = targetTurnsBandText(profile);
  const enabled = band !== null;
  const content = [
    '',
    '## 开场知情框架',
    `这是一场**长会话**：目标 ${band ?? ''} 轮。请在**前 3 轮内**用自然口语把下面五件事说清楚；`,
    '可以分轮说，但不要拖到第 5 轮之后，也不要像念条款一样一次倒完。先回应来访者当下的状态，再把框架自然带出来。',
    '',
    '### 五要素 · 硬模板（AF-133）',
    '下面每一项都给了**可以直接照着说的句式** —— 不是让你背稿，而是保证**这五件事一件都不漏**，',
    '并且把关键说法**原样留在正文里**（结构审计按这些说法判定，不要换成同义词）：',
    '',
    '1. **保密与例外**（说法：保密 / 不会告诉别人 / 例外 / 自伤 / 自杀 / 联系 / 保护你）：',
    '   “你说的话是**保密**的，我**不会告诉别人**；只有一个**例外** —— 出现**自伤**或**自杀**念头、',
    '   出现**生命危险**，或者法律要求的时候，我需要**联系**能**保护你**的人。”',
    '2. **设置边界**（说法：约定 / 框架 / 边界 / 不评判 / 不指责 / 不能替你决定）：',
    '   “我们先**约定**一下这个**框架**：这里只做咨询，我**不评判**、**不指责**，也**不能替你决定**；',
    '   你随时可以说出哪里让你不舒服。”',
    '3. **时长与频率**（说法：50 分钟 / 每周一次 / 调整）：',
    '   “我们**每次**咨询大约 **50 分钟**，**每周一次**；要**调整**时间或频率，我们可以一起商量。”',
    '4. **可暂停与可拒答**（说法：随时可以喊停 / 暂停 / 可以拒绝 / 可以跳过 / 不必勉强）：',
    '   “你**随时可以喊停**，说一声**暂停**就好；有些话题你**可以拒绝**、**可以跳过**，',
    '   **不必勉强**自己讲出来。”',
    '5. **录音与知情同意**（说法：录音 / 不录音 / 知情同意 / 征求你的同意）：',
    '   “这次**不录音**；如果以后需要**录音**或录像，我会先征求你的**同意**（**知情同意**），',
    '   你不同意就不录。”',
    '',
    '### 前 3 轮补检',
    '第 1 轮之后、第 2 轮之后、第 3 轮结束前，各在心里过一遍上面五项 —— 哪一项还没说到，',
    '就在接下来的轮次里**自然补上**，不要等到第 5 轮之后才补，也不要硬凑成一段条款朗读。',
    '',
    '语气要求：像真实咨询师的开场，不要机械罗列；框架是给来访者安全感，不是免责声明。',
    '来访者处于危机时，先做安全评估与稳定化，再补开场框架。',
  ].join('\n');

  return {
    id: 'opening-framework',
    order: 25,
    enabled,
    content,
  };
}
