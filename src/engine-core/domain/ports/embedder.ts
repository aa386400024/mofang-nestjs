// V2026-10-28 治本 (WP2 · 引擎内核 · 向量化端口):
//   职责: 定义"文本 → 向量"的最小抽象. 内核只依赖该接口, 不关心背后是
//         OpenAI 兼容厂商 / 本地模型 / 云 API.
//   边界: 纯 TS, 零 @nestjs/* / typeorm. 内核**不实现**它 —— 实现放 B 层
//         (src/engine-adapters/embedder/), 因为向量化必然要发网络请求.
//
//   反双胞胎:
//     - 不把 embedding 模型名 / 维度 / baseUrl 写进内核 —— 那些是部署环境的事,
//       内核一旦知道具体模型, 换模型就得改内核, 等于把内核绑死在某个厂商上.
//     - 不返回 provider 的原始响应类型 —— 内核只认"一个数字数组", 多余信息由 B 层
//       自行消化 (或干脆丢弃).
//     - 不在内核里放"调用失败就抛"还是"调用失败就降级"的策略 —— 降级是 B 层的
//       责任 (记忆写不进去不能炸穿 turn), 端口只声明"可能会失败".
//
//   如何验证:
//     1. pnpm build 0 错
//     2. B 层 OpenAICompatEmbedder 实现它; 内核零实现 (靠 boundary 断言保证)

/**
 * 向量化抽象: 内核只依赖该接口, 不关心是 OpenAI 兼容 / 本地模型 / 云 API.
 */
export interface Embedder {
  /**
   * 把一段文本编码为向量.
   *
   * 失败语义: 由 B 层决定降级方式 (返回空数组 / 抛错), 但**不得让异常炸穿 turn**
   * —— 记忆写不进去是"降级", 不是"会话失败".
   */
  embed(text: string): Promise<readonly number[]>;
}
