  '这种状态持续多久了？',
  '以前也有过类似的时候吗？',
  '那时候你是怎么熬过去的？',
  '你平时一天大概怎么安排？',
  '工作或学习上最近忙些什么？',
  '有没有哪件事让你觉得特别累？',
  '回到家以后，你一般会做什么？',
